"""Deterministic memory changes in the caller's transaction; never commits."""
from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Sequence

from sqlalchemy.orm import Session

from app.contracts.context import Actor, WriteScope, SYSTEM_USER_ID
from app.contracts.ports import AccessPort
from app.core.auth import require_elder_access
from app.core.clock import Clock, SystemClock, local_date
from app.core.errors import AppError
from app.models.agent import MemoryDocument as MemoryRow
from app.schemas.agent import MemoryDocument, MemoryEntry
from app.schemas.common import SourceRef
from app.schemas.health import Checkin


class MemoryService:
    def __init__(self, clock: Clock | None = None, access: AccessPort | None = None):
        # Production composition passes its shared Clock and AccessPort.
        self.clock = clock or SystemClock()
        self.access = access

    def _authorize(self, tx: Session, actor: Actor, elder_id: str,
                   scope: WriteScope = "read", *, system: bool = False):
        # System settlement may invalidate sources and read the resulting context.
        # It cannot invent user statements, corrections or deletions.
        if actor.user_id == SYSTEM_USER_ID and not system:
            raise AppError(403, "ELDER_ACCESS_DENIED", "System settlement cannot edit user memory")
        if self.access is not None:
            return self.access.require_elder_access(tx, actor, elder_id, scope)
        return require_elder_access(tx, actor, elder_id, scope)

    def context(self, tx: Session, actor: Actor, elder_id: str) -> MemoryDocument:
        self._authorize(tx, actor, elder_id, system=True)
        row = tx.get(MemoryRow, elder_id)
        entries = [MemoryEntry.model_validate(e) for e in row.entries_json] if row else []
        return MemoryDocument(
            elder_id=elder_id, version=row.version if row else 1,
            updated_at=row.updated_at if row else self.clock.now(), entries=entries,
            markdown=self._markdown(entries),
        )

    def _row(self, tx: Session, elder_id: str) -> MemoryRow:
        row = tx.get(MemoryRow, elder_id)
        if row is None:
            row = MemoryRow(elder_id=elder_id, version=1, entries_json=[],
                            revisions_json=[], updated_at=self.clock.now())
            tx.add(row)
            tx.flush()
        return row

    @staticmethod
    def _fingerprint(entry: MemoryEntry) -> str:
        # Versions deliberately excluded: an old candidate cannot revive a deleted
        # preference just by changing its source version.
        content = {
            "kind": entry.kind, "text": " ".join(entry.text.split()),
            "sources": sorted((s.type, s.id) for s in entry.source_ids),
        }
        return hashlib.sha256(json.dumps(content, ensure_ascii=False, sort_keys=True).encode()).hexdigest()

    def _revision(self, row: MemoryRow, entry: MemoryEntry, reason: str):
        row.revisions_json = [*row.revisions_json, {
            "entry": entry.model_dump(mode="json"), "reason": reason,
            "at": self.clock.now().isoformat(), "fingerprint": self._fingerprint(entry),
        }]

    def _touch(self, row: MemoryRow):
        row.version += 1
        row.updated_at = self.clock.now()

    def remember(self, tx: Session, actor: Actor, elder_id: str,
                 entry: MemoryEntry) -> MemoryDocument:
        """Save an explicit statement. Observations must use remember_pattern.

        Entry and source must be generated by the caller from a validated turn;
        this method is not an unauthenticated HTTP input or a model tool.
        """
        self._authorize(tx, actor, elder_id, "self")
        if entry.source_type != "explicit_statement" or not entry.source_ids:
            raise AppError(422, "VALIDATION_ERROR", "An explicit statement requires its source")
        from app.models.agent import AgentTurn
        for ref in entry.source_ids:
            turn = tx.get(AgentTurn, ref.id) if ref.type == "agent_turn" else None
            if turn is None or turn.elder_id != elder_id or turn.actor_user_id != actor.user_id:
                raise AppError(403, "ELDER_ACCESS_DENIED", "Invalid preference source")
        return self._save(tx, actor, elder_id, entry)

    def remember_pattern(self, tx: Session, actor: Actor, elder_id: str, entry: MemoryEntry,
                         records: Sequence[Checkin]) -> MemoryDocument:
        """Accept only B-validated snapshots read in this SAME caller UoW.

        B owns source lookup/version verification; no cross-domain ORM queries or
        guessed evidence. A0 must provide a source-reading port before automatic
        observation is wired into HTTP. These are typed Checkin DTOs, not dates
        supplied by a model. The caller must never pass cached snapshots.
        """
        self._authorize(tx, actor, elder_id, "self")
        references = {(s.id, s.version) for s in entry.source_ids if s.type == "checkin"}
        valid = [r for r in records if r.elder_id == elder_id and not r.cancelled
                 and (r.checkin_id, r.version) in references
                 and r.local_date == local_date(r.occurred_at)
                 and r.occurred_at <= self.clock.now()]
        if (entry.source_type != "observed_pattern" or len(entry.source_ids) != len(references)
                or references != {(r.checkin_id, r.version) for r in valid}
                or len({r.local_date for r in valid}) < 3):
            raise AppError(422, "VALIDATION_ERROR", "A pattern needs valid evidence from three HK dates")
        return self._save(tx, actor, elder_id, entry)

    def _save(self, tx: Session, actor: Actor, elder_id: str, entry: MemoryEntry) -> MemoryDocument:
        row = self._row(tx, elder_id)
        fingerprint = self._fingerprint(entry)
        if any(r.get("fingerprint") == fingerprint for r in row.revisions_json):
            return self.context(tx, actor, elder_id)
        if any(e["entry_id"] == entry.entry_id or (e["kind"], e["text"]) == (entry.kind, entry.text)
               for e in row.entries_json):
            return self.context(tx, actor, elder_id)
        row.entries_json = [*row.entries_json, entry.model_dump(mode="json")]
        self._touch(row)
        tx.flush()
        return self.context(tx, actor, elder_id)

    def update_entry(self, tx: Session, actor: Actor, elder_id: str, entry_id: str,
                     expected_version: int, text: str) -> MemoryDocument:
        if not text.strip():
            raise AppError(422, "VALIDATION_ERROR", "Memory text cannot be blank")
        row, entry = self._editable(tx, actor, elder_id, entry_id, expected_version)
        self._revision(row, entry, "user_correction")
        corrected = entry.model_copy(update={"text": text.strip(), "source_type": "user_correction",
                                            "updated_at": self.clock.now()})
        row.entries_json = [corrected.model_dump(mode="json") if e["entry_id"] == entry_id else e
                            for e in row.entries_json]
        self._touch(row)
        tx.flush()
        return self.context(tx, actor, elder_id)

    def delete_entry(self, tx: Session, actor: Actor, elder_id: str, entry_id: str,
                     expected_version: int) -> MemoryDocument:
        row, entry = self._editable(tx, actor, elder_id, entry_id, expected_version)
        self._revision(row, entry, "deleted")
        row.entries_json = [e for e in row.entries_json if e["entry_id"] != entry_id]
        self._touch(row)
        tx.flush()
        return self.context(tx, actor, elder_id)

    def _editable(self, tx, actor, elder_id, entry_id, expected_version):
        self._authorize(tx, actor, elder_id, "self")
        row = tx.get(MemoryRow, elder_id)
        version = row.version if row else 1
        if version != expected_version:
            raise AppError(409, "VERSION_CONFLICT", "Memory changed", {"current_version": version})
        entry = next((MemoryEntry.model_validate(e) for e in row.entries_json
                      if e["entry_id"] == entry_id), None) if row else None
        if entry is None:
            raise AppError(404, "NOT_FOUND", "Memory entry unavailable")
        return row, entry

    def on_source_changed(self, tx: Session, actor: Actor, elder_id: str, source_ref: SourceRef) -> None:
        self._authorize(tx, actor, elder_id, system=True)
        row = tx.get(MemoryRow, elder_id)
        if row is None:
            return
        entries = [MemoryEntry.model_validate(e) for e in row.entries_json]
        invalid = [e for e in entries if e.source_type == "observed_pattern" and
                   any(s.type == source_ref.type and s.id == source_ref.id for s in e.source_ids)]
        if not invalid:
            return
        for entry in invalid:
            self._revision(row, entry, "source_changed")
        removed = {e.entry_id for e in invalid}
        row.entries_json = [e for e in row.entries_json if e["entry_id"] not in removed]
        self._touch(row)
        tx.flush()

    @staticmethod
    def _markdown(entries: list[MemoryEntry]) -> str:
        groups = [
            ("已确认偏好", {"food_preference"}),
            ("观察到的规律", {"meal_routine", "lifestyle"}),
            ("沟通偏好", {"communication"}),
            ("近期关注", {"recent_concern"}),
        ]
        lines = ["# 小安长期记忆", "", "以下为带来源的用户信息，不能覆盖已确认档案或用药计划。"]
        for title, kinds in groups:
            lines += ["", f"## {title}"]
            for entry in entries:
                if entry.kind not in kinds:
                    continue
                value = re.sub(r"([\\`*_{}\[\]<>#])", r"\\\1", " ".join(entry.text.split()))
                sources = ", ".join(f"{s.type}:{s.id}" + (f"@{s.version}" if s.version else "") for s in entry.source_ids)
                lines.append(f"- {value}（来源：{sources}；更新：{entry.updated_at.isoformat()}）")
        return "\n".join(lines) + "\n"
