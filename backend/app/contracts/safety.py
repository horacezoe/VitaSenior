from typing import Protocol
from datetime import date
from sqlalchemy.orm import Session
from app.contracts.context import Actor
from app.schemas.health import DailyReport, HealthAnomaly, SafetySource, SafetyReview

class SafetyPort(Protocol):
    """Caller owns UoW; these methods perform bounded DB work, never model I/O."""
    def sources(self, tx:Session, actor:Actor, elder_id:str, day:date, report:DailyReport) -> tuple[SafetySource,...]: ...
    def read(self, tx:Session, actor:Actor, elder_id:str, day:date) -> list[HealthAnomaly]: ...
    def status(self, tx:Session, actor:Actor, elder_id:str, day:date) -> str: ...
    def reviewed(self, tx:Session, actor:Actor, elder_id:str, day:date, digest:str, model:str) -> bool: ...
    def save(self, tx:Session, actor:Actor, elder_id:str, day:date, digest:str, model:str, review:SafetyReview | None) -> None: ...
